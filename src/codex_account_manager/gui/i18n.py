def diagnostic_name(name: str) -> str:
    names = {
        "codex_cli": ("Codex CLI installation", "Codex CLI kurulumu"),
        "codex_version": ("Codex version", "Codex sürümü"),
        "shared_codex_home": ("Codex data folder", "Codex veri klasörü"),
        "session_history": ("Conversation history", "Konuşma geçmişi"),
        "database": ("Local database", "Yerel veritabanı"),
        "profile_count": ("Saved accounts", "Kayıtlı hesap sayısı"),
        "profiles": ("Account records", "Hesap kayıtları"),
        "desktop_running": ("Codex Desktop", "Codex Desktop"),
        "pending_recovery": ("Switch recovery", "Geçiş kurtarma durumu"),
        "timestamp": ("Check time (UTC)", "Kontrol zamanı (UTC)"),
    }
    if name.startswith("profile:"):
        return ("Hesap: " if language() == "tr" else "Account: ") + name.split(":", 1)[1]
    value = names.get(name)
    return value[language() == "tr"] if value else name


