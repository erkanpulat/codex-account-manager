def diagnostic_detail(name: str, ok: bool, detail: str) -> str:
    if language() != "tr":
        return detail
    messages = {
        "present": "Mevcut",
        "none": "Henüz konuşma geçmişi yok",
        "running": "Çalışıyor",
        "not running": "Şu anda kapalı; bu bir hata değildir",
        "No interrupted switch.": "Yarım kalan hesap geçişi yok.",
        "Interrupted switch requires recovery.": "Yarım kalan hesap geçişinin kurtarılması gerekiyor.",
        "Codex CLI not found on PATH.": "Codex CLI bulunamadı. Terminalde codex --version komutunu deneyin. Kurulumdan sonra bu uygulamayı yeniden açın.",
        "missing": "Bulunamadı",
    }
    if name.startswith("profile:"):
        return (
            "Giriş bilgisi: "
            + ("var" if "auth=yes" in detail else "yok")
            + " · Hesap eşleştirmesi: "
            + ("tamamlandı" if "bound=yes" in detail else "gerekli")
        )
    if name == "codex_version" and not ok:
        return (
            "Codex sürümü okunamadı. Terminalde codex --version komutunu çalıştırın, ardından uygulamayı yeniden açıp kontrolü tekrarlayın. Teknik ayrıntı: "
            + detail
        )
    return messages.get(detail, detail)


